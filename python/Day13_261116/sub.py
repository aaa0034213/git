# sub.py

import pandas as pd
import streamlit as st
from sklearn.linear_model import LinearRegression


# 오차 = 실제 - 예상
# MAE, MSE 
st.title("오차")

# 평균 몇 분 틀렸나를 숫자로 답하는 것을 MAE(평균 절대 오차)

st.header("친구가 도착 시간: 평균 몇 분 틀렸나 (MAE)")

# 실제 걸린 시간 입력!
월 = st.number_input("월요일 걸린 시간(분)", value= 10, min_value= 0)
화 = st.number_input("화요일 걸린 시간(분)", value= 10, min_value= 0)

# 표로 만든다.
표 = pd.DataFrame({
    "요일" : ["월요일","화요일"],
    "내 예상": [10,10],
    "실제 걸린 시간": [월,화]
})

# 차이 = 실제 - 예상 (많이 걸리면 +, 적게 걸리면 -)
표["차이"] = 표["실제 걸린 시간"] - 표["내 예상"]

# 차이에 크기만 본다 (마이너스 없앰)
표["차이 크기"] = 표["차이"].abs()

# 표를 보여준다.
st.write(표)

# MAE = 차이 크기의 평균
mae = 표["차이 크기"].mean()
st.write("MAE 평균적으로 틀린시간: ", f"{mae:.1f}분")


# 상황
#  - 배달앱이 4일 연속 30분 걸려요!
#  - 실제 도착은 33,28,34,27분

표 = pd.DataFrame({
    "날짜": ["1일", "2일", "3일", "4일"],
    "앱 예상": [30, 30, 30, 30],
    "실제 도착": [33, 28, 34, 27]
})

표["차이"] = 표["실제 도착"] - 표["앱 예상"]

표["차이 크기"] = 표["차이"].abs()

st.write(표)

# MAE 평균
mae = 표["차이 크기"].mean()
st.write("MAE 평균적으로 틀린시간: ", f"{mae:.1f}분")

# MAE 하는 이유
# - 머신 러닝이 만든 예상이 얼마나 맞는지 채점하는 점수표
#  컴퓨터가 한 말을 믿어도 되는지 
# - 이 모델을 믿어도 되는지, A/B 모델 중 어떤게 더 좋은지, MAE 작은 쪽 선택

