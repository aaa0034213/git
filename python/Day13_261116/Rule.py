st.subheader("배달 요금 표 맞추기")

영수증 = pd.DataFrame({
    "개수" : [1,2,3],
    "총액" : [15000,27000,39000],
})

st.write(영수증)

# 내가 추측한 숫자를 넣는 칸 step은 버튼을 누를 때마다 바뀌는 크기
기울기 = st.number_input("메뉴 1개당 가격추측: ", value= 5000, step = 1000)
기본값 = st.number_input("배달비 추측:", value = 0, step = 500)

# 내 추측으로 계산한 총액 ( y = 기울기 * X + 절편)
내예측 = 영수증["개수"] * 기울기 + 기본값

# 실제 총액과 얼마나 다른지 모두 더한다.

틀린정도 = (영수증["총액"] - 내예측).abs().sum()

st.metric("틀린 정도 ", 틀린정도)

if 틀린정도 == 0:
    st.success("요금 표를 맞췄습니다!")

