#  시험 점수를 예측하는 모델

import streamlit as st
import pandas as pd
from sklearn.linear_model import LinearRegression

# 1. 데이터
#  공부시간  점수
공부 = pd.DataFrame({"시간": [1, 2, 3, 4, 5], "점수": [52, 58, 71, 78, 88]})

# X = 표 모양 시간
# y = 점수(정답)

X = 공부[["시간"]]
y = 공부["점수"]

# 학습 : 컴퓨터가 규칙을 찾는다
model = LinearRegression()
model.fit(X,y)

# 예측: 내 예상이 아닌 컴퓨터가 예상하게
공부["모델 예상"] = model.predict(X)

# 차이 평균
공부["차이 크기"] = (공부["점수"] - 공부["모델 예상"]).abs()

st.write(공부)

mae = 공부["차이 크기"].mean()

st.write("MAE 평균적으로 틀린 시간: ", f"{mae:.1f}점")

