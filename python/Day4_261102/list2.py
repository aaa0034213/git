# 여러개의 데이터를 저장하는 타입 (List)

# 비어있는 바구니!하나가 생긴다.
장바구니 = []
print(장바구니)

#len은 사이즈구하는 기능!내가 예약했어!
장바구니개수 = len(장바구니)
print("현재 개수:",장바구니개수)

# 담기 버튼을 클릭했다는 가정하에 데이터를 추가
# 하는 기능
장바구니.append("미역국")
장바구니.append("가글")

print(장바구니)
장바구니개수 = len(장바구니)
print("현재 개수:",장바구니개수)

장바구니.append("팝콘")
장바구니.append("샴푸")

print(장바구니)
장바구니개수 = len(장바구니)
print("현재 개수:",장바구니개수)

#추가되는 데이터는 항상 뒤쪽에 들어간다.?
# 코드는 항상 위에서 아래로 실행된다?

# 삭제
print("삭제 전에는 무조건 확인", 장바구니)

# 가글 삭제!
# remove(값)
장바구니.remove("가글")
print(장바구니)

# 팝콘 삭제!
장바구니.remove("팝콘")
print(장바구니)

#이미 삭제 되었거나 없는 값이면 어떤 결과?
# 데이터가 없으면 에러!

# 먼저 데이터가 있는지 확인
# 장바구니 리스트에 팝콘이 있니?
# in 있으면 True, 없으면 False
확인 = "팝콘" in 장바구니
print(확인)

if 확인:
    장바구니.remove("팝콘")
    print(장바구니)
else:
    print("입력한 데이터가 없습니다!")

# 출근명단에서 이서희 사원이 출근 안했니?
