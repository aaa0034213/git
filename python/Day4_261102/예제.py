# 예제 1.
층 = 1
결과 = "통과"

while 층 <= 5 :
    if 층 == 5:
        결과 = "도착"
    print(f"{층}층 {결과}")
    층 += 1

print("엘레베이터 종료")

# 예제 2.
잔액 = 500
요금 = 1500

if 잔액 >= 요금:
    print("승차 승인")

else:
    print("잔액이 부족합니다")
    print(f"{요금 - 잔액}원이 부족합니다.")

결과 = "승차 가능" if 잔액 >= 요금 else "승차불가"
print(결과)

