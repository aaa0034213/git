입력 = input("아이디: ")

# 문자만 들어가는게 아니라 변수명도 들어갈 수 있음
# if 입력값이 비어있지 않다면 입력 변수값을 이름에 저장
이름 = 입력 if 입력 != "" else "익명"
print(이름)

# 응용. 내가 입력한 횟수만큼 Hello! 출력
# 횟수: 5 , Hello! 5번 출력
# 횟수: 2, Hello! 2번 출력

횟수 = int(input("횟수 입력: "))

while 횟수 > 0 :
    print("Hello")
    횟수 -= 1


# 내가 입력한 횟수만큼 줄넘기! 출력
# 횟수 : 3
# 1번째 줄넘기!
# 2번째 줄넘기!


횟수2 = int(input("줄넘기 횟수를 입력하세요: "))

while 횟수2 > 0:
    print(f"{횟수2}번째 줄넘기!")
    횟수2 -= 1


def 줄넘기(횟수):
    현재횟수 = 1

    while 현재횟수 <= 횟수:
        print(f"{현재횟수}번째 줄넘기!")
        현재횟수 += 1

횟수2 = int(input("줄넘기 횟수를 입력하세요: "))
줄넘기(횟수2)


