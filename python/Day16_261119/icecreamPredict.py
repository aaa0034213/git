# 섞기 - 여러 정보를 조합해서 더 쓸모있는 새 힌트 만드는 것
힌트 = [[20, 0, 3, 0], [25, 1, 1, 25], [30, 0, 2, 0], [22, 1, 3, 22], [28, 0, 1, 0],
       [24, 1, 2, 24], [27, 0, 3, 0], [31, 1, 1, 31], [23, 0, 2, 0], [29, 1, 3, 29]]

# 4번째 칸은 = 기온 * 주말 입니다 (평일이면 0, 주말이면 그날의 기온 1)
# 주말에는 기온의 영향이 얼마나 받아서 달라지는지
# 기온 - 기온에 따라 얼마나 판매량이 달라지는지?
# 주말 - 주말이면 판매량이 얼마나 더 늘지/줄어들지
# 기본 데이터만 있으면 예측의 정확성이 떨어지기 때문에 가지고 있는 데이터 이용해 새로운 데이터 만들어 예측
모델 = LinearRegression()
모델.fit(힌트[:8], 판매량[:8])
예측 = 모델.predict(힌트[8:])

print("예측:", 예측.round(1), "정답:", 판매량[8:])
print("평균 오차:", round(mean_absolute_error(판매량[8:], 예측), 2))
print("coef_:", 모델.coef_.round(2), "절편:", round(모델.intercept_, 2))

