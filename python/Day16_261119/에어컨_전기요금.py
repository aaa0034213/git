import streamlit as st
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error


제목 = "에어컨 전기요금 예측"
st.set_page_config(page_title=제목)         # set_page_config 웹 기본 페이지 설정하는 함수!
st.title(제목)
st.write("사용시간과 소비전력으로 요금을 예측하고, 색상과 버튼 횟수를 추가하면 예측 오차가 어떻게 달라지는지 비교!!")

# ==================================
# 1. 데이터                                 # 데이터 40개
# ==================================

사용시간 = [
    2, 3, 4, 5, 6, 2, 7, 8, 3, 5,
    1, 4, 6, 8, 2, 5, 7, 3, 9, 4,
    2, 6, 8, 5, 3, 7, 4, 10, 1, 6,
    5, 8, 2, 7, 4, 9, 3, 6, 10, 5
]
소비전력 = [
    1.0, 1.5, 1.0, 2.0, 1.5, 2.0, 1.0, 1.5, 2.0, 1.5,
    1.0, 2.0, 1.0, 2.0, 1.5, 1.0, 1.5, 1.0, 1.0, 1.5,
    2.0, 2.0, 1.0, 1.5, 2.0, 2.0, 1.0, 1.5, 2.0, 1.5,
    2.0, 1.5, 1.0, 1.0, 2.0, 1.5, 1.5, 1.0, 2.0, 1.0
]
에어컨색상 = [
    1, 2, 3, 1, 2, 3, 1, 2, 3, 1,
    3, 1, 2, 2, 1, 3, 2, 1, 3, 2,
    2, 3, 1, 3, 2, 1, 3, 2, 1, 1,
    2, 3, 2, 1, 1, 3, 2, 3, 1, 2
]
리모컨버튼횟수 = [
    5, 8, 12, 3, 10, 7, 15, 4, 11, 6,
    9, 2, 14, 6, 12, 4, 8, 15, 3, 10,
    7, 13, 5, 11, 2, 9, 14, 4, 8, 12,
    6, 15, 3, 10, 7, 2, 13, 5, 11, 9
]
전기요금 = [
    300, 675, 600, 1500, 1350, 600, 1050, 1800, 900, 1125,
    150, 1200, 900, 2400, 450, 750, 1575, 450, 1350, 900,
    600, 1800, 1200, 1125, 900, 2100, 600, 2250, 300, 1350,
    1500, 1800, 300, 1050, 1200, 2025, 675, 900, 3000, 750
]

# 입력 데이터와 정답 표 6줄

st.header("입력 데이터와 정답")
데이터표 = {
    "사용시간": 사용시간[:6],
    "소비전력": 소비전력[:6],
    "에어컨색상": 에어컨색상[:6],
    "리모컨버튼횟수": 리모컨버튼횟수[:6],
    "전기요금": 전기요금[:6]
}
st.table(데이터표)
st.write("전체 데이터 40개 중 앞의 32개는 공부용, 마지막 8개는 시험용입니다.")
st.divider()


# ==================================
# 2. 숨겨진 규칙 그래프
# ==================================

st.header("숨겨진 규칙")
st.write("전기요금 = 사용시간 × 소비전력 × 150원")
st.caption("실습용 규칙이며 실제 전기요금 계산 방식과는 다릅니다.")

조건 = st.selectbox(
    "변경할 조건",
    ["사용시간", "소비전력", "에어컨색상", "리모컨버튼횟수"]
)

if 조건 == "사용시간":
    조건값 = [1, 2, 3, 4, 5, 6, 7, 8]
    요금 = []
    for 시간 in 조건값:
        요금.append(시간 * 1.5 * 150)
    st.write("소비전력은 1.5kW로 고정합니다.")
    st.write("사용시간이 길어질수록 전기요금이 증가합니다.")

elif 조건 == "소비전력":
    조건값 = [0.5, 1.0, 1.5, 2.0, 2.5, 3.0]
    요금 = []
    for 전력 in 조건값:
        요금.append(4 * 전력 * 150)
    st.write("사용시간은 4시간으로 고정합니다.")
    st.write("소비전력이 커질수록 전기요금이 증가합니다.")

elif 조건 == "에어컨색상":
    조건값 = [1, 2, 3]
    요금 = [900] * len(조건값)
    설명 = "색상이 달라도 전기요금은 같습니다."

else:
    조건값 = [0, 5, 10, 15, 20]
    요금 = [900] * len(조건값)
    설명 = "버튼 횟수가 달라도 전기요금은 같습니다."

if 조건 in ["에어컨색상", "리모컨버튼횟수"]:
    st.write("사용시간 4시간, 소비전력 1.5kW로 고정합니다.")
    st.write(설명)

st.bar_chart(
    {조건: 조건값, "전기요금(원)": 요금},
    x=조건,
    y="전기요금(원)",
    horizontal=True
)

# ==================================
# 3. 모델
# ==================================

# 베이스라인 모델
평균 = sum(전기요금[:32]) / 32
베이스라인예측 = [평균] * len(전기요금[32:])
베이스라인오차 = mean_absolute_error(전기요금[32:], 베이스라인예측)

# 원본 데이터 40개로 두 모델의 힌트 만들기.
힌트1 = []
힌트2 = []

for i in range(len(전기요금)):
    힌트1.append([사용시간[i], 소비전력[i]])
    힌트2.append(힌트1[i] + [에어컨색상[i], 리모컨버튼횟수[i]])        # 전기요금 = 사용시간 × 소비전력 × 150원 수식과 다중회귀 모델과 맞지 않아서 따로 설정.

# 첫 번째 모델: 관련 힌트 2개
모델1 = LinearRegression()
모델1.fit(힌트1[:32], 전기요금[:32])
예측1 = 모델1.predict(힌트1[32:])
오차1 = mean_absolute_error(전기요금[32:], 예측1)

# 두 번째 모델: 쓸모없는 힌트 추가 (2개추가)
모델2 = LinearRegression()
모델2.fit(힌트2[:32], 전기요금[:32])
예측2 = 모델2.predict(힌트2[32:])
오차2 = mean_absolute_error(전기요금[32:], 예측2)

st.subheader("모델1 계수")
st.table({
    "힌트": ["사용시간", "소비전력"],
    "계수": 모델1.coef_.round(2)
})

st.subheader("모델2 계수")
st.table({
    "힌트": ["사용시간", "소비전력", "에어컨색상", "버튼횟수"],
    "계수": 모델2.coef_.round(2)
})

st.caption("다른 조건이 같을 때, 힌트가 1 증가하면 계수만큼 예측 요금이 변합니다.")         # 모델1, 모델2 coef 보기 표로 만들기...

# ==================================
# 4. 결과 확인 및 최종 비교
# ==================================

st.header("머신러닝 예측 결과")
if st.button("전기요금 예측하기"):
    st.write("베이스라인: 학습 데이터의 전기요금 평균")
    st.write("관련 힌트: 사용시간 + 소비전력")
    st.write("전체 힌트: 사용시간 + 소비전력 + 에어컨색상 + 버튼횟수")

    # 세 모델의 예측값과 실제 정답을 한 표에서 비교
    st.table({
        "시험 번호": list(range(1, len(전기요금[32:]) + 1)),
        "실제 정답(원)": 전기요금[32:],
        "베이스라인(원)": [round(x) for x in 베이스라인예측],
        "관련 힌트(원)": [round(x) for x in 예측1],
        "전체 힌트(원)": [round(x) for x in 예측2]
    })

    st.divider()                        # 영역 구분하기위해 가로 구분선 생성함수!!!!!
    st.header("최종 모델 비교")
    st.caption("평균 오차는 실제 정답과 예측값의 차이(절댓값)를 평균한 값입니다.")      # 보조 설명 텍스트 출력 함수!!

    # 모델별 오차는 한 번에 정리..!
    모델이름 = ["베이스라인", "관련 힌트", "전체 힌트"]
    공부오차 = [
        mean_absolute_error(전기요금[:32], [평균] * 32),
        mean_absolute_error(전기요금[:32], 모델1.predict(힌트1[:32])),
        mean_absolute_error(전기요금[:32], 모델2.predict(힌트2[:32]))
    ]
    시험오차 = [베이스라인오차, 오차1, 오차2]

    st.table({                                                                  # table 생성해서 보기
        "모델": 모델이름,
        "공부용 평균 오차(원)": [round(x, 2) for x in 공부오차],
        "시험 평균 오차(원)": [round(x, 2) for x in 시험오차]
    })

    st.caption("평균 오차가 작을수록 예측 요금이 정답에 가깝습니다. 공부용 오차는 작은데 시험용 오차가 훨씬 크다면 과적합을 의심할 수 있다!!!!!.")

    최소오차 = min(시험오차)
    최적모델 = [
        이름 for 이름, 오차 in zip(모델이름, 시험오차)
        if 오차 == 최소오차
    ]
    st.success(f"{', '.join(최적모델)} 모델의 시험 오차가 가장 작습니다.")    
