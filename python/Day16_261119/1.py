
import streamlit as st
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error




# ==================================
# 2. 데이터
# ==================================

사용시간 = [2, 3, 4, 5, 6, 2, 7, 8, 3, 5]
소비전력 = [1.0, 1.5, 1.0, 2.0, 1.5, 2.0, 1.0, 1.5, 2.0, 1.5]
에어컨색상 = [1, 2, 3, 1, 2, 3, 1, 2, 3, 1]
리모컨버튼횟수 = [5, 8, 12, 3, 10, 7, 15, 4, 11, 6]

전기요금 = [
    300, 675, 600, 1500, 1350,
    600, 1050, 1800, 900, 1125
]

# 입력 데이터와 정답 표 6줄
st.header("입력 데이터와 정답")

데이터표 = {
    "사용시간": 사용시간[:6],
    "소비전력": 소비전력[:6],
    "에어컨색상": 에어컨색상[:6],
    "리모컨버튼횟수": 리모컨버튼횟수[:6],
    "전기요금": 전기요금[:6]
}

st.table(데이터표)

st.write("전체 데이터 10개 중 앞의 8개는 공부용, 마지막 2개는 시험용입니다.")

st.divider()


# ==================================
# 3. 모델
# ==================================

# 베이스라인 모델
평균 = sum(전기요금[:8]) / 8

베이스라인예측 = [평균, 평균]

베이스라인오차 = mean_absolute_error(
    전기요금[8:], 베이스라인예측
)


# 첫 번째 모델: 관련 힌트 2개
힌트1 = [
    [2, 1.0], [3, 1.5], [4, 1.0], [5, 2.0], [6, 1.5],
    [2, 2.0], [7, 1.0], [8, 1.5], [3, 2.0], [5, 1.5]
]

모델1 = LinearRegression()
모델1.fit(힌트1[:8], 전기요금[:8])

예측1 = 모델1.predict(힌트1[8:])

오차1 = mean_absolute_error(
    전기요금[8:], 예측1
)


# 두 번째 모델: 쓸모없는 힌트 추가
힌트2 = [
    [2, 1.0, 1, 5], [3, 1.5, 2, 8],
    [4, 1.0, 3, 12], [5, 2.0, 1, 3],
    [6, 1.5, 2, 10], [2, 2.0, 3, 7],
    [7, 1.0, 1, 15], [8, 1.5, 2, 4],
    [3, 2.0, 3, 11], [5, 1.5, 1, 6]
]

모델2 = LinearRegression()
모델2.fit(힌트2[:8], 전기요금[:8])

예측2 = 모델2.predict(힌트2[8:])

오차2 = mean_absolute_error(
    전기요금[8:], 예측2
)


# ==================================
# 4. 결과 확인
# ==================================

st.header("머신러닝 예측 결과")

if st.button("전기요금 예측하기"):

    st.subheader("1. 베이스라인 모델")
    st.write("학습 데이터의 전기요금 평균으로 예측")
    st.write("예측 결과:", [round(x, 0) for x in 베이스라인예측])
    st.write("실제 정답:", 전기요금[8:])
    st.metric("평균 오차", f"{베이스라인오차:.2f}원")

    st.divider()

    st.subheader("2. 관련 힌트 모델")
    st.write("사용시간 + 소비전력")
    st.write("예측 결과:", 예측1.round(0))
    st.write("실제 정답:", 전기요금[8:])
    st.metric("평균 오차", f"{오차1:.2f}원")

    st.divider()

    st.subheader("3. 전체 힌트 모델")
    st.write("사용시간 + 소비전력 + 에어컨색상 + 버튼횟수")
    st.write("예측 결과:", 예측2.round(0))
    st.write("실제 정답:", 전기요금[8:])
    st.metric("평균 오차", f"{오차2:.2f}원")

    st.divider()


    # ==================================
    # 5. 최종 비교
    # ==================================

    st.header("최종 모델 비교")

    st.write("베이스라인 오차:", round(베이스라인오차, 2))
    st.write("관련 힌트 모델 오차:", round(오차1, 2))
    st.write("전체 힌트 모델 오차:", round(오차2, 2))

    if 베이스라인오차 < 오차1 and 베이스라인오차 < 오차2:
        st.success("베이스라인 모델의 오차가 가장 작습니다.")

    elif 오차1 < 베이스라인오차 and 오차1 < 오차2:
        st.success("관련 힌트 모델의 오차가 가장 작습니다.")

    elif 오차2 < 베이스라인오차 and 오차2 < 오차1:
        st.success("전체 힌트 모델의 오차가 가장 작습니다.")

    else:
        st.info("두 모델 이상의 오차가 같습니다.")