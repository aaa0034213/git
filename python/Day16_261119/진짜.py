def 평가하기(공부, 시험, 공부예측, 시험예측):
    return {
        "예측": 시험예측,
        "공부오차": mean_absolute_error(공부["전기요금"], 공부예측),
        "시험오차": mean_absolute_error(시험["전기요금"], 시험예측)
    }


def 평균으로_예측하기(공부, 시험):
    평균 = 공부["전기요금"].mean()
    return 평가하기(공부, 시험, [평균] * len(공부), [평균] * len(시험))


def 회귀모델_학습하기(공부, 시험, 힌트):
    모델 = LinearRegression()
    모델.fit(공부[힌트], 공부["전기요금"])
    결과 = 평가하기(공부, 시험, 모델.predict(공부[힌트]), 모델.predict(시험[힌트]))
    return 모델, 결과


def 계수_보여주기(제목, 힌트이름, 모델):
    st.subheader(제목)
    st.table({"힌트": 힌트이름, "계수": 모델.coef_.round(2)})


def 결과_보여주기(모델별결과, 시험정답):
    st.write("베이스라인: 학습 데이터의 전기요금 평균")
    st.write("관련 힌트: 사용시간 + 소비전력")
    st.write("전체 힌트: 사용시간 + 소비전력 + 에어컨색상 + 버튼횟수")

    예측표 = {"시험 번호": list(range(1, len(시험정답) + 1)), "실제 정답(원)": 시험정답}
    오차표 = []
    for 이름, 결과 in 모델별결과.items():
        예측표[f"{이름}(원)"] = [round(값) for 값 in 결과["예측"]]
        오차표.append({
            "모델": 이름,
            "공부용 평균 오차(원)": round(결과["공부오차"], 2),
            "시험 평균 오차(원)": round(결과["시험오차"], 2)
        })

    st.table(예측표)
    st.divider()
    st.header("최종 모델 비교")
    st.caption("평균 오차는 실제 정답과 예측값의 차이(절댓값)를 평균한 값입니다.")
    st.table(오차표)
    st.caption("평균 오차가 작을수록 예측 요금이 정답에 가깝습니다. 공부용 오차는 작은데 시험용 오차가 훨씬 크다면 과적합을 의심할 수 있습니다.")
    최소오차 = min(결과["시험오차"] for 결과 in 모델별결과.values())
    최적모델 = [이름 for 이름, 결과 in 모델별결과.items() if 결과["시험오차"] == 최소오차]
    st.success(f"{', '.join(최적모델)} 모델의 시험 오차가 가장 작습니다.")


def main():
    제목 = "에어컨 전기요금 예측"
    st.set_page_config(page_title=제목)
    st.title(제목)
    st.write("사용시간과 소비전력으로 요금을 예측하고, 색상과 버튼 횟수를 추가하면 예측 오차가 어떻게 달라지는지 비교해 봅니다.")
    데이터 = pd.DataFrame(기록, columns=전체힌트)
    if len(데이터) < 2:
        st.warning("공부용과 시험용으로 나누려면 기록이 2건 이상 필요합니다.")
        return
    데이터["전기요금"] = 요금_계산하기(데이터["사용시간"], 데이터["소비전력"])
    학습개수 = int(len(데이터) * 0.8)
    공부 = 데이터.iloc[:학습개수]
    시험 = 데이터.iloc[학습개수:]

    입력표_보여주기(데이터, 학습개수)
    규칙_보여주기()

    모델1, 관련결과 = 회귀모델_학습하기(공부, 시험, 관련힌트)
    모델2, 전체결과 = 회귀모델_학습하기(공부, 시험, 전체힌트)

    계수_보여주기("모델1 계수", 관련힌트, 모델1)
    계수_보여주기("모델2 계수", 전체힌트, 모델2)
    st.caption("다른 조건이 같을 때, 힌트가 1 증가하면 계수만큼 예측 요금이 변합니다.")

    st.header("머신러닝 예측 결과")
    if st.button("전기요금 예측하기"):
        모델별결과 = {"베이스라인": 평균으로_예측하기(공부, 시험), "관련 힌트": 관련결과, "전체 힌트": 전체결과}
        결과_보여주기(모델별결과, 시험["전기요금"].tolist())


if __name__ == "__main__":
    main()

