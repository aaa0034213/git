# 운동 기록앱!
# 운동 앱에 지난 운동 기록 30분, 45분, 60분이 저장되어 있습니다.

# 오늘 운동 시간을 입력하면 기록 맨 뒤에 추가하고,
# 직전 운동 기록과 비교해서 결과를 알려 줍니다.
# - 오늘 운동 시간이 더 길면 → "늘었어요"
# - 오늘 운동 시간이 같으면 → "같아요"
# - 오늘 운동 시간이 더 짧으면 → "줄었어요"

# 1. 앱이 저장해 둔것은?
#   30,45,60
# 2. 앱이 하는 일을 순서대로 작성?
#  -1) 지난 운동기록을 저장한다.
#  -2) 오늘 운동 시간을 입력한다.
    #    리스트에 바로 추가했을때
#  -3) 마지막 기록과 바로 이전 기록을 비교한다.
#   #    리스트에 바로 추가 안했을 때
#  -3) 마지막기록과 오늘 운동시간입력한 변수랑 비교한다.
#       오늘 운동시간을 리스트에 추가한다.
# 3. 몇번째 값을 꺼내나?/어디서부터 어디까지 짜르나?
#    리스트에 추가했다면 -1 , -2
#    리스트 추가 안했다면 -1 , 입력한운동시간

# 1. 운동시간 기록 변수(리스트)
운동기록 = [30,45,60]
print(운동기록)
while True:
    # 2. 오늘 운동 시간 입력!
    오늘 = int(input("오늘 운동시간 입력:(분)"))

    # 3. 리스트에 추가
    운동기록.append(오늘)
    print(운동기록)

    직전운동시간 = 운동기록[-2]
    오늘운동시간 = 운동기록[-1]

    if 오늘운동시간 > 직전운동시간:
        print("늘었어요!")
    elif 오늘운동시간 < 직전운동시간:
        print("줄었어요!")
    else :
        print("같아요!")

