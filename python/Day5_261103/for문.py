# 공항! 수화물검사
수화물검색대 = ['🎁','👜','🧨','🧸','📱']

#
for 수화물 in 수화물검색대[:]:
    print("현재 수화물:", 수화물)
    print()
    if 수화물 == '🧨' :
        수화물검색대.remove(수화물)
    if 수화물 == '🧸':
        수화물검색대.remove(수화물)


print()
print(수화물검색대)