# 회사 출근 확인 앱
# 회사에서 오늘 출근한 직원들의 이름을 리스트에 저장했습니다.

# ["민수", "지영", "철수", "수빈", "영희"]

# 관리자는 특정 직원이 출근했는지 확인하고 싶습니다.

# 1. 앱이 저장해 둔것은?
# 오늘 출근한 사람들!
출근명단 = ["민수", "지영", "철수", "수빈", "영희"]

# 2.앱이 하는 일을 순서대로 작성?
#  -1) 출근한 직원의 이름을 리스트에 저장한다
#  -2) 관리자가 확인할 직원의 이름을 입력한다.
#  -3) 입력한 이름이 리스트에 있는지 확인한다.
#  -4) 있다면 직원의 위치를 번호를 찾아 출력한다.
#  -5) 없다면 출근하지 않았습니다!

# 3.몇번째 값을 꺼내나?/어디서부터 어디까지 짜르나?
# 중복되지 않은 값
이름 = input("검색할 직원명:")

if 이름 in 출근명단:
    print("출근확인")
    print(출근명단.index(이름) +1 ,"번째 출근함")
else:
    print("노 출근!")